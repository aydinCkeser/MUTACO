"""Run the readable six-parameter frozen-GP target-matching experiment."""

from __future__ import annotations

import argparse
from pathlib import Path
from time import perf_counter
from typing import Any

import mutaco
import mutaco_analytic
from mutaco import RuntimeRequest, resolve_runtime

if __package__:
    from ._support import (
        build_manifest,
        load_config,
        prepare_profiles,
        run_and_assess_profile,
        write_json,
    )
else:
    from _support import (
        build_manifest,
        load_config,
        prepare_profiles,
        run_and_assess_profile,
        write_json,
    )


REPOSITORY_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_CONFIG = (
    REPOSITORY_ROOT
    / "experiments"
    / "analytic_target_matching"
    / "configs"
    / "gp_landscape.json"
)
DEFAULT_OUTPUT = (
    REPOSITORY_ROOT / "runs" / "analytic_target_matching" / "gp_landscape"
)


def execute(
    *,
    config_path: Path,
    output: Path,
    requested_device: str = "auto",
) -> dict[str, Any]:
    """Match a hidden target generated by the frozen-GP mock forward."""

    # 1. Read the scientific choices and select CUDA or the visible CPU fallback.
    config = load_config(config_path)
    if set(config["profiles"]) != {"gp_landscape"}:
        raise ValueError(
            "GP-landscape experiment requires exactly one gp_landscape profile"
        )
    runtime = resolve_runtime(
        RuntimeRequest(device=requested_device, dtype=str(config["dtype"]))
    )

    # 2. Build the frozen landscape, generate y(theta_star), and hide theta_star.
    output.mkdir(parents=True, exist_ok=True)
    started = perf_counter()
    (profile,) = prepare_profiles(
        config,
        device=runtime.torch_device,
        dtype=runtime.torch_dtype,
    )

    # 3. Run MUTACO with visible progress, replay it, and write results and plots.
    result = run_and_assess_profile(
        profile,
        output=output,
        device=runtime.torch_device,
    )

    # 4. Record runtime provenance without changing the scientific identity.
    manifest = build_manifest(
        config=config,
        config_paths=(config_path,),
        runtime=runtime,
        results=(result,),
        total_runtime_seconds=perf_counter() - started,
        package_origins={
            "mutaco": str(Path(mutaco.__file__).resolve()),
            "mutaco_analytic": str(Path(mutaco_analytic.__file__).resolve()),
        },
        cuda_command=(
            "python -m experiments.analytic_target_matching.run_gp_landscape "
            f"--config {config_path.as_posix()} --output <output> --device cuda"
        ),
    )
    write_json(output / "manifest.json", manifest)
    print(
        "[analytic target matching] completed GP-landscape experiment on "
        f"{runtime.effective_device} in {manifest['total_runtime_seconds']:.3f}s; "
        f"outputs: {output}"
    )
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--config",
        type=Path,
        default=DEFAULT_CONFIG,
    )
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--device",
        choices=("auto", "cpu", "cuda"),
        default="auto",
    )
    arguments = parser.parse_args()
    execute(
        config_path=arguments.config,
        output=arguments.output,
        requested_device=arguments.device,
    )


if __name__ == "__main__":
    main()
